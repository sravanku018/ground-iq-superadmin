/** Auto-expand "<alias> gen|sc|st" reservation-suffix variants. */
export function withReservationSuffixes(base: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [alias, name] of Object.entries(base)) {
    out[alias] = name;
    out[`${alias} gen`] = name;
    out[`${alias} sc`] = name;
    out[`${alias} st`] = name;
  }
  return out;
}

